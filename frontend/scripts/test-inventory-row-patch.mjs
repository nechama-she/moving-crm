import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const exports={};
vm.runInNewContext(ts.transpileModule(readFileSync(new URL('../src/inventoryRowPatch.ts',import.meta.url),'utf8'),
  {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports});
const {inventoryRowPatch}=exports;
const catalog=[{id:'chair',name:'Chair',cuft:30},{id:'table',name:'Table',cuft:12}];
const original=[{id:'room',room_type_id:'bedroom',name:'Bedroom',items:{chair:1,table:2}}];
const next=structuredClone(original);
next[0].items.chair=10;
let patch=inventoryRowPatch(original,next,catalog);
assert.equal(patch.expected.quantity,1);
assert.equal(patch.changes.quantity,10);
assert.equal(patch.room,'Bedroom');
const custom=structuredClone(original);
custom[0].items.chair=0;
custom[0].custom_items=[{id:'uuid',catalog_item_id:'chair',name:'Chair',cuft:30,quantity:10}];
patch=inventoryRowPatch(original,custom,catalog);
assert.equal(patch.changes.quantity,10);
const newer=structuredClone(custom);
newer[0].custom_items[0].quantity=11;
assert.equal(inventoryRowPatch(custom,newer,catalog).expected.quantity,10);
assert.equal(inventoryRowPatch(original,original,catalog),null);
assert.equal(inventoryRowPatch(null,next,catalog),null);
const renamed=structuredClone(next);renamed[0].name='Office';
assert.equal(inventoryRowPatch(original,renamed,catalog),null);
console.log('Row edits produce one targeted patch, including catalog-to-custom edits.');
