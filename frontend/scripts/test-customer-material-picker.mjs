import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import vm from 'node:vm';
import ts from 'typescript';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const require=createRequire(import.meta.url);
const exports={};
const source=readFileSync(new URL('../src/CustomerMaterialItems.tsx',import.meta.url),'utf8');
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX}}).outputText,{exports,require});
const item={label:'Queen mattress',inventory_id:'m',quantity:1,service:'self'};
const html=renderToStaticMarkup(React.createElement(exports.default,{config:{material_quotes:[{id:'m',status:'priced',packing_only:12,packing_and_material:38}]},selection:{additional_items:{m:item}},onChange:()=>{},disabled:false}));
assert.match(html,/Queen mattress/);
assert.match(html,/Packing only/);
assert.match(html,/\$12\.00/);
assert.match(html,/Packing and material/);
assert.match(html,/\$38\.00/);
assert.match(html,/Add items from inventory/);
assert(!html.includes('Mattress size'));
assert(!html.includes('Calculate materials'));
assert(!html.includes('type="number"'));
console.log('Inventory packing rows show purchase choices without material or size questions.');
