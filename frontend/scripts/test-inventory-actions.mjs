import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const exports={};
vm.runInNewContext(ts.transpileModule(readFileSync(new URL('../src/inventoryActions.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports});
const {inventoryActions}=exports;
const catalog=[{id:'chair',name:'Chair',cuft:30},{id:'table',name:'Table',cuft:12}];
const before=[{id:'room',room_type_id:'bedroom',name:'Bedroom',items:{chair:1,table:2}}];
const diff=(after)=>JSON.parse(JSON.stringify(inventoryActions(before,after,catalog)));
let after=structuredClone(before);after[0].items.chair=10;after[0].items.table=3;
assert.deepEqual(diff(after).map(row=>row.kind),['row_update','row_update']);
after=structuredClone(before);after[0].items.chair=0;
assert.deepEqual(diff(after).map(row=>row.kind),['row_remove']);
after=structuredClone(before);after[0].name='Office';
assert.deepEqual(diff(after),[{kind:'room_rename',room:'Bedroom',name:'Office',room_type_id:'bedroom'}]);
assert.deepEqual(diff([]),[{kind:'room_remove',room:'Bedroom'}]);
after=structuredClone(before);after.push({id:'new',name:'Living Room',room_type_id:'bedroom',items:{chair:1}});
assert.deepEqual(diff(after).map(row=>row.kind),['room_add','row_add']);
after=structuredClone(before);after[0].items.chair=0;after[0].custom_items=[{id:'custom',name:'Chair',catalog_item_id:'chair',quantity:10,cuft:30}];
assert.deepEqual(diff(after).map(row=>row.kind),['row_update']);
assert.deepEqual(diff(before),[]);
console.log('Inventory additions, removals, renames, and batched row edits send only their actions.');
