import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../src/googlePlaces.ts', import.meta.url), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } });
const { addressRequest } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const requests=[];
globalThis.fetch=async (url,options)=>{requests.push({url,options});return {ok:true,json:async()=>({suggestions:[]})};};
const controller=new AbortController();
await addressRequest('/api/public-moves/id','link','session','address-search',{text:'Miami',session_token:'uuid'},controller.signal);
assert.equal(requests.length,1);
assert.equal(requests[0].url,'/api/public-moves/id/address-search');
assert.equal(requests[0].options.signal,controller.signal);
assert.equal(requests[0].options.headers['x-public-session'],'session');
assert.equal(requests[0].options.method,'POST');
assert.equal(requests[0].options.cache,'no-store');
globalThis.fetch=async()=>({ok:false,json:async()=>({detail:'Search unavailable'})});
await assert.rejects(()=>addressRequest('/api/public-moves/id','link','session','address-search',{},controller.signal),/Search unavailable/);
console.log('Address search: authenticated CRM-only background requests and errors passed.');
